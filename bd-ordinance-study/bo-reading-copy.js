function formatProvisionReading(section, entries) {
  const mentions = new Map();
  return entries.map(([label, source]) => {
    // Scope bilingual repetitions to a subsection, including when only one paragraph is shown.
    const scope = label.match(/^\([\dA-Za-z]+\)/)?.[0] ?? label.split(/[｜(]/, 1)[0];
    if (!mentions.has(scope)) mentions.set(scope, new Set());
    const seen = mentions.get(scope);
    const edited = boReadingEdits[section]?.[label];
    const text = (edited ?? source.replace(boReadingPhrasePattern, phrase => boReadingPhrases[phrase])
      .replace(/^凡係(?=(?:Building Authority|任何|建築事務監督|根據|在|喺|由))/u, "如果")
      .replace(/([，；])就就(?=第)/gu, "$1就"))
      .replace(boReadingTermPattern, (full, english, chinese, explicit, abbr) => {
        if (abbr) {
          const [long, translation] = boReadingShortTerms[abbr];
          if (seen.has(long)) return full;
          seen.add(long);
          return `${long}（${translation}，${abbr}）`;
        }
        if (seen.has(english)) return explicit ?? chinese;
        seen.add(english);
        return full;
      });
    return { label, text };
  });
}
