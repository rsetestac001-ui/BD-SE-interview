function recoveryWorkflow(unregisteredPath, registeredPath, originalPayer, completionPayer) {
  return fork("屋宇署代辦後，命令有冇登記？",
    route("未登記", end(`可向${originalPayer}追費`, unregisteredPath)),
    route("已登記", end(`可向${completionPayer}追費`, registeredPath)));
}

