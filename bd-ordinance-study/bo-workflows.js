// A sequence continues after a fork only when its branch does not end the route.
const step = (label, path = "", section = "", note = "") => ({ label, path, section, note });
const end = (label, path, section, note) => ({ ...step(label, path, section, note), terminal: true });
const fork = (label, ...branches) => ({ label, branches });
const route = (label, ...steps) => ({ label, steps });

function inspectionWorkflow(building) {
  const section = building ? "§30B" : "§30C";
  const appointment = building ? "§30D" : "§30E";
  const inspection = building ? "驗樓" : "驗窗";
  const person = building ? "註冊檢驗人員（RI）" : "合資格人士（QP）";
  const deadlines = building ? "(7)" : "(5)";
  return [
    step("核對樓齡、適用範圍同通知收件人", "(1)", section,
      `樓齡門檻 ${building ? 30 : 10} 年。第 30A(2) 條排除三層或以下住用建築物。`),
    fork("業主收到法定通知未？",
      route("未收到", end("等候通知；未觸發今次法定檢驗", "(3)", section)),
      route("已收到", fork("屬正常辦理，定已逾限期仍未遵從？",
        route("正常辦理", step(`按限期委任${person}做訂明${inspection}`, deadlines + "(a)", section),
          step(`完成訂明${inspection}`, deadlines + "(b)", section),
          fork("驗出危險，或者日後可能變危險？",
            route("有，要修葺", step(`搵註冊承建商修葺，由${person}監督`, "(1)", appointment),
              step("完成修葺，交適用報告／證明書", deadlines + "(c)", section)),
            route("無，毋須修葺", step("交適用嘅檢驗文件同證明書", deadlines + "(b)", section))),
          end(`確認遵從後，同一${building ? "部分 10" : "隻窗 5"} 年內有再發通知限制`, building ? "(12)" : "(10)", section,
            "由原通知日期起計。")),
        route("逾限期未遵從", step("建築事務監督可安排代驗或代修", building ? "(10)" : "(8)", section),
          fork("代辦後追費：通知有冇土地註冊？",
            route("無", end("可向原收通知嘅人追費", building ? "(11)(a)" : "(9)(a)", section)),
            route("有", end("可向代辦工作完成當日嘅相關業主追費", building ? "(11)(b)" : "(9)(b)", section)))))))
  ];
}

function disciplineWorkflow(contractor) {
  const section = contractor ? "§13" : "§7";
  return [
    step("收到涉嫌違規或失職嘅資料", contractor ? "(2)" : "(1A)", section),
    fork("事由同嚴重程度符合轉介門檻？",
      route("未符合", end("呢條紀律途徑到此為止", "(1)", section)),
      route("符合", step("建築事務監督可轉介紀律個案", "(1)", section,
        contractor ? "公司或合夥個案另查第 (3) 款可一併轉介嘅人士。" : ""),
        step("局長按條文委任紀律委員會成員", "(1)", contractor ? "§11" : "§5",
          `委員團提供人選。組成細節睇第 ${contractor ? "11、11A" : "5、5A"} 條。`),
        fork("研訊後，委員會信納事由成立？",
          route("唔成立", end("無依呢項事由作處分命令", contractor ? "(4)" : "(2)", section)),
          route("成立", step("委員會可作紀律命令", contractor ? "(4)" : "(2)", section),
            step("作出命令後，裁斷同命令須登憲報", contractor ? "(4A)" : "(2A)", section),
            end("被命令人如不服，可向原訟法庭法官上訴", contractor ? "(7)" : "(4)(a)", section)))))
  ];
}

