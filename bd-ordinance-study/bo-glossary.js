const glossaryAliases = new Map(boGlossary.flatMap(entry => {
  const [english, chinese, , , aliases = []] = entry;
  return [english, chinese, ...aliases].map(alias => [alias.toLowerCase(), entry]);
}));
const escapeGlossaryPattern = value => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const glossaryAliasPattern = (english, paired) => [...glossaryAliases]
  .filter(([alias, entry]) => /^[a-z]/i.test(alias) === english && (!glossaryPairedOnly.has(entry[0]) || paired))
  .map(([alias]) => alias)
  .sort((a, b) => b.length - a.length)
  .map(escapeGlossaryPattern)
  .join("|");
const glossaryBilingualSuffix = String.raw`\s*[（(](?:[^()（）\n]{0,36}[\p{Script=Han}][^()（）\n]{0,36}|[A-Z]{2,6})[）)]`;
